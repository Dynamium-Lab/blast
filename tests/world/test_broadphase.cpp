  DynamicSphere spheres;
  spheres.start_time = 0;
  spheres.end_time   = 1;
  for (Vec3 c: centers) {
    sphere.center = c;
    spheres.trajectory.push_back(sphere);
  }

  spheres.n_points = spheres.trajectory.size();

  World world;
  world.dynamic_spheres = {spheres};

  return world;
